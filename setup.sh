#!/usr/bin/env bash
# setup.sh — Connect Claude Code to a NousResearch Hermes model
# Supports Ollama (local) or any OpenAI-compatible API endpoint.

set -euo pipefail

###############################################################################
# Configuration
###############################################################################

# Default: Ollama running locally with the Hermes model
DEFAULT_API_BASE="http://localhost:11434/v1"
DEFAULT_MODEL="NousResearch/Hermes-3-Llama-3.1-8B"

HERMES_API_BASE="${HERMES_API_BASE_URL:-$DEFAULT_API_BASE}"
HERMES_MODEL="${HERMES_MODEL:-$DEFAULT_MODEL}"
HERMES_API_KEY="${HERMES_API_KEY:-ollama}"

###############################################################################
# Helpers
###############################################################################

info()  { echo "[INFO]  $*"; }
warn()  { echo "[WARN]  $*" >&2; }
error() { echo "[ERROR] $*" >&2; exit 1; }

###############################################################################
# Pre-flight checks
###############################################################################

check_claude_installed() {
  if ! command -v claude &>/dev/null; then
    error "Claude Code CLI not found. Install it with: npm install -g @anthropic-ai/claude-code"
  fi
  info "Claude Code CLI found: $(claude --version 2>/dev/null || echo 'version unknown')"
}

check_api_reachable() {
  info "Testing connection to Hermes API at: $HERMES_API_BASE"
  if curl -sf --max-time 5 "$HERMES_API_BASE/models" \
       -H "Authorization: Bearer $HERMES_API_KEY" -o /dev/null; then
    info "API endpoint is reachable."
  else
    warn "Could not reach $HERMES_API_BASE — make sure your Hermes server is running."
    warn "  Ollama example: ollama serve && ollama pull $HERMES_MODEL"
  fi
}

###############################################################################
# Environment setup
###############################################################################

export_env_vars() {
  export ANTHROPIC_BASE_URL="$HERMES_API_BASE"
  export ANTHROPIC_API_KEY="$HERMES_API_KEY"
  info "ANTHROPIC_BASE_URL=$ANTHROPIC_BASE_URL"
  info "ANTHROPIC_API_KEY=$ANTHROPIC_API_KEY"
}

write_env_file() {
  local env_file=".env.hermes"
  cat > "$env_file" <<EOF
# Generated by setup.sh — Claude Code ↔ Hermes connection
ANTHROPIC_BASE_URL=$HERMES_API_BASE
ANTHROPIC_API_KEY=$HERMES_API_KEY
HERMES_MODEL=$HERMES_MODEL
EOF
  info "Environment written to $env_file"
  info "  Source it in your shell: source $env_file"
}

###############################################################################
# Pull model via Ollama (optional)
###############################################################################

pull_ollama_model() {
  if command -v ollama &>/dev/null; then
    info "Pulling Hermes model via Ollama: $HERMES_MODEL"
    ollama pull "$HERMES_MODEL" || warn "Model pull failed — you may need to pull it manually."
  else
    info "Ollama not found — skipping model pull."
    info "  Install Ollama: https://ollama.com/download"
  fi
}

###############################################################################
# Main
###############################################################################

main() {
  info "=== Claude Code ↔ Hermes Setup ==="
  info "Model : $HERMES_MODEL"
  info "API   : $HERMES_API_BASE"
  echo

  check_claude_installed
  pull_ollama_model
  check_api_reachable
  export_env_vars
  write_env_file

  echo
  info "Setup complete."
  info "Run Claude Code with the Hermes model:"
  info "  source .env.hermes && claude --model $HERMES_MODEL"
}

main "$@"
